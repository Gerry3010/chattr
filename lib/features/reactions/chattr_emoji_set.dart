import 'package:emoji_picker_flutter/emoji_picker_flutter.dart';
import 'package:emoji_picker_flutter/locales/default_emoji_set_locale.dart';
import 'package:flutter/widgets.dart';

import 'emoji_supplement.g.dart';

/// The package's emoji set, supplemented by what it lacks.
///
/// `emoji_picker_flutter` supplies about 1350 of the roughly 1650 Unicode base
/// emoji. The gaps are not a fringe matter — 🪦, the new heart colours 🩷🩵🩶, 🫀,
/// 🥲, the gender-neutral professions 🧑‍⚕️🧑‍💻 and nearly 280 more are missing
/// entirely, so they are findable neither in the grid nor through search. A
/// package update does not fix it: 4.5.3 has exactly the same gaps.
///
/// It supplements rather than replaces. The package set stays untouched —
/// including its curated keyword lists in eleven languages — and every added
/// emoji carries an **anchor**: the last emoji before it that the package
/// knows. Both follow from that, the category and the insertion point. 🪦
/// thereby lands behind ⚰️ and not at the end of the grid, and we need no
/// mapping of our own from Unicode group to [Category], which would quietly go
/// wrong with the next package version.
///
/// The data behind it is generated by `scripts/gen-emoji-supplement.py`.

/// Variation selector 16 — turns a text character into an emoji.
///
/// Package and Unicode data disagree on whether it belongs (`⚰` vs `⚰️`), so
/// both sides are normalised for matching the anchors.
const String _vs16 = '️';

String _withoutVs16(String s) => s.replaceAll(_vs16, '');

final Map<String, List<CategoryEmoji>> _zwischenspeicher = {};

/// The emoji set for [locale], supplemented and in the chosen [skinTone].
///
/// Passed as `Config.emojiSet`. The result is built once per language and skin
/// tone and memoised — the picker asks afresh on every opening.
List<CategoryEmoji> chattrEmojiSet(Locale locale, {String skinTone = ''}) =>
    _zwischenspeicher.putIfAbsent(
      '${locale.languageCode}|$skinTone',
      () => applySkinTones(
        supplementEmojiSet(getDefaultEmojiLocale(locale), locale),
        skinTone,
      ),
    );

/// Applies [skinTone] to every emoji that knows skin tones.
///
/// Tinted with `EmojiPickerUtils.applySkinTone` — **deliberately not with
/// character arithmetic of our own.** The long-press selection uses the same
/// function, and both routes must produce the same character sequence: a
/// reaction is compared by its text, and a second 👍🏽 composed differently could
/// no longer be taken back by tapping.
List<CategoryEmoji> applySkinTones(List<CategoryEmoji> basis, String skinTone) {
  if (skinTone.isEmpty) return basis;
  final werkzeug = EmojiPickerUtils();
  return [
    for (final category in basis)
      CategoryEmoji(category.category, [
        for (final emoji in category.emoji)
          if (emoji.hasSkinTone) werkzeug.applySkinTone(emoji, skinTone) else emoji,
      ]),
  ];
}

/// Inserts the missing emoji into [basis] — each directly behind its anchor.
///
/// For [locale] only the language counts: German gets the German keywords,
/// everything else the English ones (the package does the same; its
/// `getDefaultEmojiLocale` falls back to English).
///
/// Public so the test can do without the package set.
List<CategoryEmoji> supplementEmojiSet(
  List<CategoryEmoji> basis,
  Locale locale, {
  List<SupplementEmoji> supplement = supplementEmoji,
}) {
  final german = locale.languageCode == 'de';

  final byAnchor = <String, List<Emoji>>{};
  for (final n in supplement) {
    byAnchor.putIfAbsent(_withoutVs16(n.anchor), () => []).add(
          Emoji(n.character, german ? n.de : n.en, hasSkinTone: n.skinTone),
        );
  }

  // An anchor can appear in several categories; insertion happens only at the
  // first match, otherwise the same emoji would stand twice in the grid.
  final consumed = <String>{};

  return [
    for (final category in basis)
      CategoryEmoji(category.category, [
        for (final emoji in category.emoji) ...[
          emoji,
          if (byAnchor.containsKey(_withoutVs16(emoji.emoji)) &&
              consumed.add(_withoutVs16(emoji.emoji)))
            ...byAnchor[_withoutVs16(emoji.emoji)]!,
        ],
      ]),
  ];
}

/// The anchors for which there is no matching emoji in [basis].
///
/// Empty as long as the package set and the generated file fit together. If
/// anything turns up here, an emoji has **silently disappeared** — which is
/// exactly what `test/chattr_emoji_set_test.dart` checks after every package
/// update.
Set<String> anchorsWithoutMatch(
  List<CategoryEmoji> basis, {
  List<SupplementEmoji> supplement = supplementEmoji,
}) {
  final vorhanden = {
    for (final k in basis)
      for (final e in k.emoji) _withoutVs16(e.emoji),
  };
  return {
    for (final n in supplement)
      if (!vorhanden.contains(_withoutVs16(n.anchor))) n.anchor,
  };
}
