// Forward secrecy (audit P3/L1): envelope v5 round-trip + the FS guarantee.
// v5 wraps the message key to a ONE-TIME prekey instead of the recipient's
// static chat key; once the prekey's private half is deleted, the SAME
// ciphertext can never be unwrapped again — that is forward secrecy, and this
// test proves it without any DB or network.
//
// Requires the native lib — run `./native/build.sh` first; skips otherwise.

import 'dart:convert';
import 'dart:io';

import 'package:chattr/core/crypto/message_context.dart';
import 'package:chattr/core/crypto/ml_kem_ffi.dart' show mlKemLibraryPathOverride;
import 'package:chattr/core/security/chat_key_pair_manager.dart';
import 'package:chattr/core/security/kem_key_binding.dart';
import 'package:chattr/core/security/message_encryption_service.dart';
import 'package:flutter/foundation.dart'
    show debugDefaultTargetPlatformOverride, TargetPlatform;
import 'package:flutter_secure_storage/flutter_secure_storage.dart';
import 'package:flutter_test/flutter_test.dart';

void main() {
  const libPath = 'native/chattr_crypto/build/libchattr_crypto.so';
  final skip =
      File(libPath).existsSync() ? false : 'native lib not built ($libPath)';

  late MessageEncryptionService svc;

  setUpAll(() {
    if (skip == false) mlKemLibraryPathOverride = libPath;
    debugDefaultTargetPlatformOverride = TargetPlatform.linux;
  });
  tearDownAll(() => debugDefaultTargetPlatformOverride = null);
  setUp(() {
    FlutterSecureStorage.setMockInitialValues({});
    svc = MessageEncryptionService(ChatKeyPairManager(const FlutterSecureStorage()));
  });

  const chatId = 'chat-fs';
  const userId = 'bob';
  const prekeyId = 'pk-xyz';
  final context = MessageContext(
    chatId: chatId,
    senderId: 'alice',
    messageId: 'msg-1',
  );

  /// A one-time prekey: a detached hybrid keypair whose public blob carries a
  /// signature (the send gate requires a signed prekey — presence is enough for
  /// the crypto; identity verification is the warn-only layer elsewhere).
  Future<({String signedPub, String priv})> makePrekey() async {
    final kp = await ChatKeyPairManager.generateDetachedKeyPair();
    return (
      signedPub: KemKeyBinding.attachSignature(kp.publicKey, 'sig-placeholder'),
      priv: kp.privateKey,
    );
  }

  test('a claimed prekey produces a v5 envelope that round-trips', () async {
    final pre = await makePrekey();
    final staticKp = await ChatKeyPairManager.generateDetachedKeyPair();

    final out = await svc.encryptForAllMembers(
      'forward-secret hello',
      {userId: staticKp.publicKey},
      context: context,
      signatureB64: 'ident-sig',
      recipientPrekeys: {
        userId: (prekeyId: prekeyId, publicBlob: pre.signedPub),
      },
    );

    final env = jsonDecode(out[userId]!) as Map<String, dynamic>;
    expect(env['v'], 5);
    expect(env['pk'], prekeyId);
    expect(env['sig'], 'ident-sig'); // same identity signature as v4

    // Decrypt with a resolver that returns the prekey's private half.
    final dec = await svc.decryptEnvelope(
      out[userId]!,
      staticKp.privateKey, // ignored for v5; the resolver key is used
      context: context,
      prekeyResolver: (id) async => id == prekeyId ? pre.priv : null,
    );
    expect(dec.plaintext, 'forward-secret hello');
    expect(dec.version, 5);
    expect(dec.prekeyId, prekeyId); // caller must delete this prekey
  }, skip: skip);

  test('FS: once the prekey is gone, the same ciphertext is undecryptable',
      () async {
    final pre = await makePrekey();
    final staticKp = await ChatKeyPairManager.generateDetachedKeyPair();

    final out = await svc.encryptForAllMembers(
      'top secret',
      {userId: staticKp.publicKey},
      context: context,
      recipientPrekeys: {
        userId: (prekeyId: prekeyId, publicBlob: pre.signedPub),
      },
    );

    // Prekey deleted (consumed) → resolver returns null → hard failure. This is
    // the forward-secrecy guarantee: a logged ciphertext cannot be recovered
    // even with the static chat key in hand.
    expect(
      () => svc.decryptEnvelope(
        out[userId]!,
        staticKp.privateKey,
        context: context,
        prekeyResolver: (_) async => null,
      ),
      throwsA(isA<Object>()),
    );
  }, skip: skip);

  test('cross-impl: decrypts a v5 envelope produced by the MCP server', () async {
    // Fixture generated by mcp_server's crypto_interop.test.ts — proves the v5
    // ek/msg/AAD byte layout + the `pk` selector match across implementations.
    final fixture = jsonDecode(
      File('web_crypto/testdata/interop_v5.json').readAsStringSync(),
    ) as Map<String, dynamic>;
    final prekeyPriv =
        jsonEncode({'x': fixture['xPriv'], 'm': fixture['mPriv']});
    final ctx = MessageContext(
      chatId: fixture['chatId'] as String,
      senderId: fixture['senderId'] as String,
      messageId: fixture['messageId'] as String,
    );

    final env = await svc.decryptEnvelope(
      fixture['envelope'] as String,
      'static-key-unused-for-v5',
      context: ctx,
      prekeyResolver: (id) async =>
          id == fixture['prekeyId'] ? prekeyPriv : null,
    );
    expect(env.version, 5);
    expect(env.plaintext, fixture['plaintext']);
    expect(env.prekeyId, fixture['prekeyId']);

    // Once the prekey is gone (resolver returns null) the Node-made ciphertext
    // is undecryptable — forward secrecy holds across implementations too.
    await expectLater(
      svc.decryptEnvelope(
        fixture['envelope'] as String,
        'static-key-unused-for-v5',
        context: ctx,
        prekeyResolver: (_) async => null,
      ),
      throwsA(anything),
    );
  }, skip: skip);

  test('an unsigned prekey is NOT used — falls back to v4', () async {
    final kp = await ChatKeyPairManager.generateDetachedKeyPair();
    final staticKp = await ChatKeyPairManager.generateDetachedKeyPair();
    // A signed static key marks the recipient as a v4 client, so the fallback
    // from a rejected prekey lands on v4 (not the v3 legacy path).
    final signedStatic =
        KemKeyBinding.attachSignature(staticKp.publicKey, 'static-sig');

    final out = await svc.encryptForAllMembers(
      'hi',
      {userId: signedStatic},
      context: context,
      signatureB64: 'ident-sig',
      recipientPrekeys: {
        // No signature attached → gate must reject and fall through to v4.
        userId: (prekeyId: prekeyId, publicBlob: kp.publicKey),
      },
    );
    expect(jsonDecode(out[userId]!)['v'], 4);
  }, skip: skip);
}
